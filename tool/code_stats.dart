// Counts how many lines of CaretNotes' source were written with AI help and writes
// lib/core/code_stats.g.dart, which Settings shows. Run from the project root:
//
//   dart run tool/code_stats.dart
//
// Uses the last commit (HEAD); uncommitted changes are not counted. Run it before a release.
import 'dart:io';

import 'package:caret_notes/core/code_stats.dart';

Future<String> git(List<String> args) async {
  final r = await Process.run('git', args, stdoutEncoding: const SystemEncoding());
  if (r.exitCode != 0) throw Exception('git ${args.join(' ')} failed: ${r.stderr}');
  return r.stdout as String;
}

/// Every commit up to and including this one was made with Claude (the owner's call;
/// the early ones just lack the Co-Authored-By trailer). Later commits count as AI-made
/// only with that trailer.
const allAiThrough = 'cb90831c3018649f2866bf067b0e4d67cb71bc5c';

Future<void> main() async {
  // Every commit, and whether an AI is named as co-author.
  final log = await git(['log', '--format=%H%x09%(trailers:key=Co-Authored-By,valueonly,separator=%x2C)']);
  final ai = <String>{};
  var commits = 0;
  for (final line in log.split('\n')) {
    final tab = line.indexOf('\t');
    if (tab < 0) continue;
    commits++;
    if (isAiCoAuthor(line.substring(tab + 1))) ai.add(line.substring(0, tab));
  }
  ai.addAll((await git(['rev-list', allAiThrough])).split('\n').map((s) => s.trim()).where((s) => s.isNotEmpty));

  final totals = <String, int>{}, aiTotals = <String, int>{};
  final files = (await git(['ls-files'])).split('\n').map((s) => s.trim()).where((s) => s.isNotEmpty);
  for (final f in files) {
    final area = codeAreaOf(f);
    if (area == null) continue;
    // Skip files added but never committed.
    String blame;
    try {
      blame = await git(['blame', '-l', '-s', 'HEAD', '--', f]);
    } catch (_) {
      continue;
    }
    for (final MapEntry(key: sha, value: n) in blameLinesByCommit(blame).entries) {
      totals[area] = (totals[area] ?? 0) + n;
      if (ai.contains(sha)) aiTotals[area] = (aiTotals[area] ?? 0) + n;
    }
  }

  final head = (await git(['rev-parse', '--short', 'HEAD'])).trim();
  final date = (await git(['log', '-1', '--format=%cs'])).trim();
  const order = ['App code', 'Tests', 'Tools, build and platform code'];
  final areas = [
    for (final a in order)
      if (totals.containsKey(a)) "    CodeArea('$a', ${totals[a]}, ${aiTotals[a] ?? 0}),",
  ];
  final out = '''// GENERATED by tool/code_stats.dart from commit $head. Do not edit by hand.
import 'code_stats.dart';

const codeStats = CodeStats(
  commit: '$head',
  date: '$date',
  commits: $commits,
  aiCommits: ${ai.length},
  areas: [
${areas.join('\n')}
  ],
);
''';
  File('lib/core/code_stats.g.dart').writeAsStringSync(out);
  final s = CodeStats(commit: head, date: date, commits: commits, aiCommits: ai.length, areas: [
    for (final a in order)
      if (totals.containsKey(a)) CodeArea(a, totals[a]!, aiTotals[a] ?? 0),
  ]);
  stdout.writeln('${s.aiLines} of ${s.lines} lines (${(s.aiShare * 100).round()} %) from ${ai.length} of $commits commits made with AI.');
}
